/* #/cosmos: solar wind, magnetosphere bow shock and LEO/MEO/GEO constellations at Keplerian speeds. Canvas 2D + SVG HUD. Exposes window.__cosmos. */
(function () {
  "use strict";
  var host = document.getElementById("cs-root");
  if (!host || host.dataset.ready) return; host.dataset.ready = "1";
  var root = document.documentElement, reduce = window.matchMedia && matchMedia("(prefers-reduced-motion: reduce)").matches;
  var GM = 398600.4418, RE = 6371; // km^3/s^2, km
  function lite() { return root.classList.contains("lite"); }
  function f(n, d) { return Number(n).toLocaleString("en-US", { maximumFractionDigits: d == null ? 0 : d, minimumFractionDigits: d == null ? 0 : d }); }
  function ev(n) { try { window.dispatchEvent(new CustomEvent("cosmos:event", { detail: n })); } catch (e) {} }
  var W = 800, H = 560, cx = 400, cy = 280, RPX = 26;
  // Orbit radius in Earth radii -> pixels. Compressed (power 0.62) so LEO and GEO fit one screen: a visual scale, not a true one.
  function px(re) { return RPX * Math.pow(Math.max(re, 0.01), 0.62); }
  function unpx(p) { return Math.pow(p / RPX, 1 / 0.62); }
  var S = { warp: 600, vsw: 400, n: 5, bz: 0, leoAlt: 550, leoN: 24, meoAlt: 20200, meoN: 24, geoN: 6, parts: [], t0: performance.now(), tsim: 0, last: 0 };

  host.innerHTML =
    '<div class="ec-grid"><div class="ec-stage"><canvas id="csCv" width="800" height="560" role="img" aria-label="Simulated solar wind deflecting around Earth magnetosphere with LEO, MEO and GEO satellite rings"></canvas>' +
    '<svg id="csHud" viewBox="0 0 800 560" aria-hidden="true"></svg><p class="ec-hint">Orbits use a compressed visual scale. Speeds and periods are computed from v = √(GM/r).</p></div>' +
    '<div class="ec-side"><div class="ec-card"><h2>Orbit mechanics</h2><dl class="ec-dl" id="csOrb" aria-live="polite"></dl></div>' +
    '<div class="ec-card"><h2>Controls</h2><label class="lbl" for="csWarp">Time warp <b id="csWarpV"></b></label><input type="range" id="csWarp" min="0" max="500" value="280"/>' +
    '<label class="lbl" for="csV">Solar wind speed <b id="csVV"></b></label><input type="range" id="csV" min="250" max="1000" value="400"/>' +
    '<label class="lbl" for="csN">Density <b id="csNV"></b></label><input type="range" id="csN" min="1" max="60" value="5"/>' +
    '<label class="lbl" for="csB">IMF Bz <b id="csBV"></b></label><input type="range" id="csB" min="-30" max="30" value="0"/></div>' +
    '<div class="ec-card"><h2>Magnetosphere</h2><dl class="ec-dl" id="csMag" aria-live="polite"></dl><p class="ec-note">Earth\'s dipole field is generated by the liquid outer-core dynamo. <a href="#/earth-core">Dive to the core →</a></p></div></div></div>';
  var $ = function (id) { return document.getElementById(id); };
  var cv = $("csCv"), c = cv.getContext("2d");

  /* Shue (1997) magnetopause: r0 = (10.22 + 1.29 tanh(0.184 (Bz + 8.14))) Pdyn^(-1/6.6); r = r0 (2/(1+cos t))^a */
  function mag() {
    var pd = 1.6726e-6 * S.n * S.vsw * S.vsw; // nPa
    var r0 = (10.22 + 1.29 * Math.tanh(0.184 * (S.bz + 8.14))) * Math.pow(pd, -1 / 6.6), a = (0.58 - 0.007 * S.bz) * (1 + 0.024 * Math.log(pd));
    return { pd: pd, r0: r0, a: a, bs: r0 * 1.3 };
  }
  function rmp(M, th) { return M.r0 * Math.pow(2 / (1 + Math.cos(th)), M.a); }
  function orbit(alt) { var r = RE + alt, v = Math.sqrt(GM / r), T = 2 * Math.PI * r / v; return { r: r, re: r / RE, v: v, T: T, w: v / r }; }
  var GEO = { r: 42164, re: 42164 / RE }; GEO.v = Math.sqrt(GM / GEO.r); GEO.T = 2 * Math.PI * GEO.r / GEO.v; GEO.w = GEO.v / GEO.r;
  function dur(s) { return s < 7200 ? f(s / 60, 1) + " min" : f(s / 3600, 2) + " h"; }

  function seed() {
    var n = lite() ? 70 : 240, i; S.parts = [];
    for (i = 0; i < n; i++) S.parts.push({ x: Math.random() * W, y: Math.random() * H, v: 0.6 + Math.random() * 0.8, k: i % 3 });
  }
  function hud() {
    var M = mag(), L = orbit(S.leoAlt), Me = orbit(S.meoAlt);
    $("csWarpV").textContent = f(S.warp) + "×"; $("csVV").textContent = S.vsw + " km/s"; $("csNV").textContent = S.n + " /cm³"; $("csBV").textContent = (S.bz > 0 ? "+" : "") + S.bz + " nT";
    $("csOrb").innerHTML = "<dt>LEO " + f(S.leoAlt) + " km</dt><dd>" + f(L.v, 2) + " km/s · " + dur(L.T) + "</dd><dt>MEO " + f(S.meoAlt) + " km</dt><dd>" + f(Me.v, 2) + " km/s · " + dur(Me.T) + "</dd><dt>GEO 35,786 km</dt><dd>" + f(GEO.v, 2) + " km/s · " + dur(GEO.T) + "</dd>";
    $("csMag").innerHTML = "<dt>Dynamic pressure</dt><dd>" + f(M.pd, 2) + " nPa</dd><dt>Magnetopause</dt><dd>" + f(M.r0, 1) + " Re (~" + f(M.r0 * RE) + " km)</dd><dt>Bow shock (approx.)</dt><dd>" + f(M.bs, 1) + " Re</dd><dt>GEO inside?</dt><dd>" + (M.r0 < GEO.re ? "NO: GEO exposed to solar wind" : "yes (" + GEO.re.toFixed(1) + " Re)") + "</dd>";
    var g = '<g fill="none" stroke-dasharray="3 5" stroke-width="1">';
    [[L, "LEO", "#06b6d4"], [Me, "MEO", "#8b5cf6"], [GEO, "GEO", "#e8f7fb"]].forEach(function (o) { var p = px(o[0].re); g += '<circle cx="' + cx + '" cy="' + cy + '" r="' + p.toFixed(1) + '" stroke="' + o[2] + '" opacity=".45"/><text x="' + (cx + p * 0.71 + 4).toFixed(0) + '" y="' + (cy + p * 0.71 + 12).toFixed(0) + '" fill="' + o[2] + '" font-size="11" font-family="monospace" stroke="none">' + o[1] + "</text>"; });
    g += '</g><text x="16" y="28" fill="#9aa7b8" font-size="11" font-family="monospace">SUN ←  solar wind ' + S.vsw + " km/s</text>";
    $("csHud").innerHTML = g;
  }

  function frame(now, dt) {
    var M = mag(), tp = now / 1000, i, p;
    c.clearRect(0, 0, W, H);
    // dipole field lines r = L sin^2(theta), compressed by the same px() map
    c.lineWidth = 1; c.setLineDash([5, 7]); c.lineDashOffset = -tp * 10;
    [2, 3, 4.5, 6].forEach(function (Ls, n) {
      if (Ls > M.r0 - 0.5) return; c.strokeStyle = n % 2 ? "rgba(139,92,246,.5)" : "rgba(6,182,212,.5)";
      [-1, 1].forEach(function (sg) { c.beginPath(); for (var a = 0.12; a < Math.PI - 0.1; a += 0.06) { var r = Ls * Math.sin(a) * Math.sin(a); if (r < 1.02) continue; var q = px(r); var xx = cx + sg * q * Math.sin(a), yy = cy - q * Math.cos(a); c.lineTo(xx, yy); } c.stroke(); });
    });
    c.setLineDash([]);
    // magnetopause + bow shock curves (sun on the left, theta measured from the sun line)
    [[1, "rgba(6,182,212,.9)"], [1.3, "rgba(139,92,246,.7)"]].forEach(function (cfg) {
      c.strokeStyle = cfg[1]; c.lineWidth = 1.6; c.beginPath(); var first = true;
      for (var th = 0; th < 2.5; th += 0.05) { var r = rmp(M, th) * cfg[0], q = px(r); var xx = cx - q * Math.cos(th), yy = cy - q * Math.sin(th); first ? c.moveTo(xx, yy) : c.lineTo(xx, yy); first = false; }
      c.stroke(); c.beginPath(); first = true;
      for (th = 0; th < 2.5; th += 0.05) { r = rmp(M, th) * cfg[0]; q = px(r); xx = cx - q * Math.cos(th); yy = cy + q * Math.sin(th); first ? c.moveTo(xx, yy) : c.lineTo(xx, yy); first = false; }
      c.stroke();
    });
    // Earth + dynamo core glow
    var g = c.createRadialGradient(cx - 6, cy - 6, 2, cx, cy, RPX); g.addColorStop(0, "#9be8ff"); g.addColorStop(0.6, "#0b3b57"); g.addColorStop(1, "#06b6d4"); c.fillStyle = g; c.beginPath(); c.arc(cx, cy, RPX, 0, 6.2832); c.fill();
    c.fillStyle = "rgba(249,115,22,.9)"; c.beginPath(); c.arc(cx, cy, 5, 0, 6.2832); c.fill();
    // solar wind particles: advected rightwards, pushed around the bow shock
    var sp = S.vsw / 400 * 55;
    for (i = 0; i < S.parts.length; i++) {
      p = S.parts[i]; var dx = p.x - cx, dy = p.y - cy, rr = Math.sqrt(dx * dx + dy * dy), re = unpx(rr), th = Math.atan2(Math.abs(dy), -dx);
      var vx = sp * p.v, vy = 0, lim = rmp(M, Math.min(2.4, Math.max(0, th))) * 1.3;
      if (dx < 40 && re < lim + 1.2 && re > 0.2) { var push = (lim + 1.2 - re) / 1.2; vx = sp * p.v * (0.35 + 0.1 * push) + dx / rr * 20 * push; vy = (dy >= 0 ? 1 : -1) * 55 * push + dy / rr * 30 * push; }
      p.x += vx * dt; p.y += vy * dt;
      if (p.x > W + 4 || p.y < -4 || p.y > H + 4 || rr < RPX) { p.x = -4; p.y = Math.random() * H; p.v = 0.6 + Math.random() * 0.8; }
      c.fillStyle = p.k === 0 ? "rgba(6,182,212,.8)" : p.k === 1 ? "rgba(139,92,246,.8)" : "rgba(232,247,251,.5)"; c.fillRect(p.x, p.y, 2, 2);
    }
    // constellations at Keplerian angular velocity w = sqrt(GM/r^3)
    var ts = S.tsim, rings = [[orbit(S.leoAlt), S.leoN, "#06b6d4", 2.2, true], [orbit(S.meoAlt), S.meoN, "#8b5cf6", 2.6, false], [GEO, S.geoN, "#e8f7fb", 3.2, false]];
    rings.forEach(function (rg, ri) {
      var o = rg[0], pr = px(o.re), n = rg[1], j, pos = [];
      for (j = 0; j < n; j++) { var a = j / n * 6.2832 + o.w * ts + ri; pos.push([cx + pr * Math.cos(a), cy + pr * Math.sin(a)]); }
      if (rg[4]) { c.strokeStyle = "rgba(6,182,212,.22)"; c.lineWidth = 0.7; c.beginPath(); for (j = 0; j < n; j++) { c.moveTo(pos[j][0], pos[j][1]); c.lineTo(pos[(j + 1) % n][0], pos[(j + 1) % n][1]); c.moveTo(pos[j][0], pos[j][1]); c.lineTo(pos[(j + 3) % n][0], pos[(j + 3) % n][1]); } c.stroke(); }
      c.fillStyle = rg[2]; pos.forEach(function (q) { c.beginPath(); c.arc(q[0], q[1], rg[3], 0, 6.2832); c.fill(); });
    });
  }

  var onRoute = false, vis = true;
  var loop = Gov.loop("cosmos", function (now, dt) { if (!reduce) S.tsim += dt * S.warp; frame(now, reduce ? 0 : dt); }, { fps: 50, liteFps: 24, once: reduce, when: function () { return onRoute && vis; } });
  function wake() { if (onRoute && vis) loop.start(); }
  if ("IntersectionObserver" in window) new IntersectionObserver(function (e) { vis = e[0].isIntersecting; wake(); }).observe(cv);
  function sync() { onRoute = location.hash === "#/cosmos"; if (onRoute) { ev("cosmos"); wake(); } }
  window.addEventListener("hashchange", sync); document.addEventListener("visibilitychange", wake);

  function bind(id, key, conv, evn) { $(id).addEventListener("input", function (e) { S[key] = conv(+e.target.value); hud(); wake(); if (evn) ev(evn); }); }
  bind("csWarp", "warp", function (v) { return Math.round(Math.pow(10, v / 100)); }, "warp");
  bind("csV", "vsw", function (v) { return v; }, "wind"); bind("csN", "n", function (v) { return v; }); bind("csB", "bz", function (v) { return v; }, "bz");
  seed(); hud(); sync(); if (reduce) frame(performance.now(), 0);
  window.addEventListener("resize", function () { }, { passive: true });
  window.__cosmos = {
    set: function (o) {
      ["vsw", "n", "bz", "leoAlt", "leoN", "meoAlt", "meoN", "geoN", "warp"].forEach(function (k) { if (o[k] != null) S[k] = o[k]; });
      if (o.warp != null) $("csWarp").value = Math.log10(Math.max(1, S.warp)) * 100; $("csV").value = S.vsw; $("csN").value = Math.min(60, S.n); $("csB").value = S.bz; hud(); wake();
    }, state: function () { return JSON.parse(JSON.stringify({ vsw: S.vsw, n: S.n, bz: S.bz, leoAlt: S.leoAlt, meoAlt: S.meoAlt, warp: S.warp })); }, mag: mag
  };
  $("csWarp").value = Math.log10(S.warp) * 100;
})();
