// npm run gen → src/data/generated.js
// QR code for the live URL and daily commit counts from this repo's git history,
// precomputed so the site needs no QR library or API at runtime.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import QRCode from "qrcode";
import { site } from "../src/data/portfolioData.js";

const qr = QRCode.create(site.url, { errorCorrectionLevel: "M" });
const n = qr.modules.size, d = qr.modules.data;
let path = "";
for (let y = 0; y < n; y++) {
  for (let x = 0; x < n; x++) {
    if (!d[y * n + x]) continue;
    let run = 1;
    while (x + run < n && d[y * n + x + run]) run++;
    path += `M${x} ${y}h${run}v1h-${run}z`;
    x += run - 1;
  }
}

// One entry per commit (deduped across branches), counted per day for the last 26 weeks.
const lines = execSync("git log --all --format=%H%x20%ad --date=short", { encoding: "utf8" }).trim().split("\n");
const perDay = {};
for (const [, day] of new Map(lines.map((l) => l.split(" "))).entries()) perDay[day] = (perDay[day] || 0) + 1;
const end = new Date(); end.setUTCHours(0, 0, 0, 0);
const days = [];
for (let i = 26 * 7 - 1; i >= 0; i--) {
  const t = new Date(end); t.setUTCDate(end.getUTCDate() - i);
  const k = t.toISOString().slice(0, 10);
  days.push([k, perDay[k] || 0]);
}

const out = `// Generated by scripts/gen-data.mjs. Run \`npm run gen\` after changing site.url.
export const qr = ${JSON.stringify({ url: site.url, size: n, path })};
export const activity = ${JSON.stringify({ repo: "Vini-portfolio-", total: lines.length, days })};
`;
writeFileSync(new URL("../src/data/generated.js", import.meta.url), out);
console.log(`qr ${n}x${n}, ${lines.length} commits, ${days.filter((x) => x[1]).length} active days`);
